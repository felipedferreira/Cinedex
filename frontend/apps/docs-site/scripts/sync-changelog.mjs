// Copies the repo-root CHANGELOG.md into src/pages/changelog.md so Docusaurus
// serves it at /changelog. The root file is the single source of truth (see
// the "Edit only the root CHANGELOG.md" rule in the repo's CLAUDE.md) — this
// script is the only thing that should ever write to the destination file.
import { mkdirSync, readFileSync, watch, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

// scripts/ -> docs-site/ -> apps/ -> frontend/ -> repo root
const ROOT_CHANGELOG = resolve(__dirname, '../../../../CHANGELOG.md');
const DEST = resolve(__dirname, '../src/pages/changelog.md');

const REPO_BLOB_URL = 'https://github.com/felipedferreira/Cinedex/blob/main/';

// CHANGELOG.md links to other repo files with paths relative to the repo
// root (e.g. `docs/auth-security-model.md`), which resolve on GitHub but not
// as routes on this site - it only hosts a handful of pages, not the whole
// repo. Rewrite them to absolute GitHub URLs so they stay clickable; leave
// already-absolute links (http/https), in-page anchors (#...) and
// site-relative links (/...) untouched.
function rewriteRepoRelativeLinks(markdown) {
  return markdown.replace(
    /\]\((?!https?:\/\/|#|\/)([^)]+)\)/g,
    (_match, path) => `](${REPO_BLOB_URL}${path})`,
  );
}

// Docusaurus renders pages through MDX, which parses `<` as the start of a
// JSX tag rather than as CommonMark's raw-HTML-comment syntax - a literal
// `<!-- comment -->` fails the build. Rewrite to MDX's own comment syntax,
// which round-trips as an invisible comment the same way.
function mdxSafeComments(markdown) {
  return markdown.replace(
    /<!--([\s\S]*?)-->/g,
    (_match, comment) => `{/*${comment}*/}`,
  );
}

function sync() {
  const content = mdxSafeComments(
    rewriteRepoRelativeLinks(readFileSync(ROOT_CHANGELOG, 'utf-8')),
  );
  const page = `---
title: Changelog
description: Version history for Cinedex, generated from the repository's root CHANGELOG.md.
---

{/* AUTO-GENERATED by frontend/apps/docs-site/scripts/sync-changelog.mjs.
    Do not edit this file directly - edit the root CHANGELOG.md instead. */}

${content}`;

  mkdirSync(dirname(DEST), { recursive: true });
  writeFileSync(DEST, page);
}

sync();

if (process.argv.includes('--watch')) {
  console.log(`[sync-changelog] watching ${ROOT_CHANGELOG}`);

  let timer;
  watch(ROOT_CHANGELOG, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      sync();
      console.log(
        '[sync-changelog] CHANGELOG.md changed, regenerated changelog.md',
      );
    }, 150);
  });
}
